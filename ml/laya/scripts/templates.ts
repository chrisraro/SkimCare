/**
 * Hand-written sentence templates for the Laya triage dataset. All fictional.
 *
 * Syntax: `{a|b|c}` picks one alternative (nestable); `[SLOT]` is filled by
 * fillers.ts (amounts, dates, durations, names, items…). Slots with the same name
 * get the same value within one example; `[ITEM2]` is a second, different item.
 *
 * Labelling conventions (mirroring src/ai/llm/prompt.ts and the fixture labels):
 * - payment_amount: states a price/amount; no triggering event or deadline as the point.
 * - payment_condition: what must happen before money is paid (approval, delivery,
 *   inspection, receipt, advance-before-work), without a calendar deadline as the point.
 * - due_date: when a payment or task is due (day of month, date, "within N days").
 * - late_fee: a fee, interest or penalty for paying late or missing a payment.
 * - termination: how the agreement ends, its term/expiry, cancellation, repossession,
 *   stopping work for non-payment, or what happens when it ends early.
 * - notice_period: sentences whose point is the notice requirement itself (how much
 *   notice, before what). "X may terminate…" is termination; "X must give 30 days'
 *   notice before terminating" is notice_period.
 * - other: a substantive obligation or rule that is none of the above (confidentiality,
 *   house rules, warranty, leave, non-compete, insurance, utilities…).
 * - none: text that passes the app's prefilter but states no term: recitals, legal
 *   boilerplate (governing law, venue, severability, entire agreement, counterparts),
 *   section captions, signature/witness/date lines, table headers, notes to the reader,
 *   definitions, and text addressed to an AI/reader (prompt injection).
 *
 * The dev split uses different templates: within each (label, language) group every
 * 5th template (index % 5 === 4) is dev-only. Dev also uses different name/item pools.
 */
