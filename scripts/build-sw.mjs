#!/usr/bin/env node
/**
 * Writes dist/sw.js after `npx expo export -p web`.
 *
 * Precaches every same-origin file in dist/ so the app shell opens in airplane
 * mode after one visit. The cache name carries a content hash of dist/, so each
 * deploy gets a fresh cache and old ones are deleted on activate.
 *
 * Cross-origin requests (e.g. the AI model download, which @wllama/wllama caches
 * itself) and non-GET requests are never touched by the worker.
 *
 * Plain Node, no dependencies. Usage: node scripts/build-sw.mjs [distDir]
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = process.argv[2] ?? 'dist';
const MAX_BYTES = 50 * 1024 * 1024; // Skip anything this large; it does not belong in an install-time precache.
// vendor/ holds the in-browser engine runtimes (~50 MB); cacheFirst stores only the files a browser actually uses.
const SKIP = [/^sw\.js$/, /^vendor\//, /\.map$/, /(^|\/)\./, /\.DS_Store$/];

function walk(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    return e.isDirectory() ? walk(p) : [p];
  });
}

const hash = createHash('sha256');
const urls = [];
for (const file of walk(DIST).sort()) {
  const rel = relative(DIST, file).split(sep).join('/');
  if (SKIP.some((re) => re.test(rel))) continue;
  const size = statSync(file).size;
  if (size > MAX_BYTES) {
    console.warn(`build-sw: skipping ${rel} (${(size / 1048576).toFixed(1)} MB) from precache`);
    continue;
  }
  hash.update(rel).update(readFileSync(file));
  urls.push('/' + encodeURI(rel));
}
if (!urls.includes('/index.html')) {
  console.error(`build-sw: ${DIST}/index.html not found. Run \`npx expo export -p web\` first.`);
  process.exit(1);
}

const version = hash.digest('hex').slice(0, 12);

const sw = `/* Generated by scripts/build-sw.mjs. Do not edit. */
const CACHE = 'skimcare-${version}';
const PRECACHE = ${JSON.stringify(urls, null, 2)};
const NAV_TIMEOUT_MS = 4000;

self.addEventListener('install', (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('skimcare-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// The page asks for this only while it is hidden, so an update never swaps mid-review.
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('fetch', (event) => {
  const req = event.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    event.respondWith(networkFirst(req));
  } else {
    event.respondWith(cacheFirst(req));
  }
});

// Navigations: fresh HTML when online, cached SPA shell when offline or on a stalled connection.
async function networkFirst(req) {
  try {
    const res = await Promise.race([
      fetch(req),
      new Promise((_, reject) => setTimeout(() => reject(new Error('timeout')), NAV_TIMEOUT_MS)),
    ]);
    if (res.ok) return res;
    throw new Error('bad status');
  } catch {
    return (await caches.match('/index.html', { cacheName: CACHE })) || (await caches.match('/index.html')) || Response.error();
  }
}

// Static assets: hashed file names, so the cached copy is always right.
async function cacheFirst(req) {
  const hit = await caches.match(req, { ignoreSearch: true });
  if (hit) return hit;
  const res = await fetch(req);
  if (res.ok && res.type === 'basic') {
    const copy = res.clone();
    caches.open(CACHE).then((cache) => cache.put(req, copy));
  }
  return res;
}
`;

writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`build-sw: wrote ${DIST}/sw.js (cache skimcare-${version}, ${urls.length} files)`);
